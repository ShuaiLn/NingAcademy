import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
const revision = '525f9b560de45753a5ea01069454e72e9aa541c6';
const source = `https://raw.githubusercontent.com/hermitdave/FrequencyWords/${revision}/content/2018/en/en_50k.txt`;
const directory = 'public/local-ai-assets/dictionary/frequencywords-v1';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const check = process.argv.includes('--check');
mkdirSync(directory, { recursive: true });
const original = check ? readFileSync(directory + '/source.txt') : Buffer.from(await (await fetch(source)).arrayBuffer());
const words = [...new Set(original.toString('utf8').trim().split('\n').map(line => line.split(' ')[0].normalize('NFKC').toLowerCase())
  .filter(word => /^[a-z]+(?:['-][a-z]+)*$/.test(word)))].sort();
const bytes = Buffer.from(words.join('\n') + '\n');
if (words.length !== 48412 || bytes.length !== 390710) throw Error('Authoritative dictionary candidate mismatch');
const offsets = Buffer.alloc((words.length + 1) * 4); let cursor = 0;
for (let i = 0; i < words.length; i++) { offsets.writeUInt32LE(cursor, i * 4); cursor += Buffer.byteLength(words[i]) + 1; }
offsets.writeUInt32LE(cursor, words.length * 4);
const assets = [['words.utf8', bytes], ['offsets.u32le', offsets]];
const manifest = { version: 1, revision, source, sourceSha256: hash(original), count: words.length,
  transformation: "NFKC; lowercase; ASCII letters with internal apostrophe/hyphen; deduplicate; byte sort; LF including final LF; little-endian uint32 offsets with terminal offset",
  license: 'CC-BY-SA-4.0', attributionApproval: null, provenanceApproval: null, distributionApproved: false,
  assets: assets.map(([name, buffer]) => ({ id: 'dictionary-' + name, kind: 'ocr', version: '1', source: 'hermitdave/FrequencyWords@' + revision,
    bytes: buffer.length, sha256: hash(buffer), license: 'CC-BY-SA-4.0', url: '/local-ai-assets/dictionary/frequencywords-v1/' + name, cacheSchemaVersion: 1 })) };
const outputs = [...assets.map(([name, buffer]) => [directory + '/' + name, buffer]), [directory + '/source.txt', original],
  ['docs/personalized-english/phase2/dictionary.v1.json', Buffer.from(JSON.stringify(manifest, null, 2) + '\n')],
  ['app/_lib/ocr-import/dictionary-assets.generated.ts', Buffer.from('// Generated by build-dictionary.mjs. Distribution approval remains pending.\nexport const DICTIONARY_ASSETS = ' + JSON.stringify(manifest.assets, null, 2) + ' as const;\n')]];
for (const [path, content] of outputs) {
  if (check) { if (!readFileSync(path).equals(content)) throw Error('Dictionary artifact drift: ' + path); }
  else writeFileSync(path, content);
}
console.log('Dictionary candidate verified: 48,412 entries / 390,710 bytes; approval pending.');
